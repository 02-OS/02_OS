#!/usr/bin/env python3
"""Stage the verified browser packages in the live image for its installer."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'profile/airootfs/usr/local/share/02os/browser-repo'
MARKER = '.02os-generated-browser-repo'


def clean():
    if not DESTINATION.exists() and not DESTINATION.is_symlink():
        return
    marker = DESTINATION / MARKER
    if DESTINATION.is_symlink() or not marker.is_file() or marker.is_symlink():
        raise ValueError(f'Refusing to remove an unmarked browser repository: {DESTINATION}')
    shutil.rmtree(DESTINATION)


def stage(source):
    source = source.resolve(strict=True)
    manifest_path = source / 'manifest.json'
    if manifest_path.is_symlink():
        raise ValueError('Browser manifest must be a regular file')
    manifest = json.loads(manifest_path.read_text())
    packages = manifest['packages']
    if manifest['format_version'] != 1 or manifest['architecture'] != 'x86_64':
        raise ValueError('Unsupported browser repository manifest')
    if len(packages) != 2 or {package['name'] for package in packages} != {'google-chrome', 'brave-bin'}:
        raise ValueError('Both stable browser packages are required')
    repository = manifest['repository']
    if repository['name'] != '02os-browsers':
        raise ValueError('Unexpected browser repository name')
    entries = [(package['filename'], package['sha256']) for package in packages]
    entries += [(repository['filename'], repository['sha256']),
                (repository['database_filename'], repository['database_sha256'])]
    for name, digest in entries:
        if not re.fullmatch(r'[A-Za-z0-9._+-]+', name) or name in ('.', '..', 'manifest.json', MARKER):
            raise ValueError('Unsafe repository file name')
        path = source / name
        if path.is_symlink() or not path.is_file():
            raise ValueError(f'Repository artifact must be a regular file: {name}')
        with path.open('rb') as stream:
            actual = hashlib.file_digest(stream, 'sha256').hexdigest()
        if actual != digest:
            raise ValueError(f'Browser artifact checksum mismatch: {name}')
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    temporary = Path(tempfile.mkdtemp(prefix='.browser-repo-', dir=DESTINATION.parent))
    try:
        temporary.chmod(0o755)
        for name, _ in entries:
            shutil.copyfile(source / name, temporary / name)
        shutil.copyfile(manifest_path, temporary / 'manifest.json')
        (temporary / MARKER).write_text('Generated by scripts/stage-browser-repo.py\n')
        clean()
        temporary.rename(DESTINATION)
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)
    print(f'Staged Chrome and Brave packages in {DESTINATION}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, nargs='?', default=ROOT / '.cache/browser-repo')
    parser.add_argument('--clean', action='store_true')
    args = parser.parse_args()
    clean() if args.clean else stage(args.source)
